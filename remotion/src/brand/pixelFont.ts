/** Lit cells of a text line, as [col, row] offsets from its top-left (4 columns per character). */
export function textCells(text: string): [number, number][] {
  const out: [number, number][] = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const g = G[ch] ?? G["?"];
    g.forEach((row, y) => [...row].forEach((c, x) => { if (c === "#") out.push([i * 4 + x, y]); }));
  });
  return out;
}
export const textWidth = (text: string) => text.length * 4 - 1;
